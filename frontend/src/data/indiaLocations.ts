/**
 * Returns all State & UT names, sorted alphabetically within their group
 */
export const STATES_LIST = INDIA_STATES_AND_UTS.filter(s => s.type === 'State').map(s => s.name);
export const UTS_LIST = INDIA_STATES_AND_UTS.filter(s => s.type === 'UT').map(s => s.name);

/**
 * Given a State or UT name, returns the list of all districts belonging to it.
 * If not found or empty, returns an empty array.
 */
export function getDistrictsForState(stateName: string): string[] {
  if (!stateName) return [];
  const found = INDIA_STATES_AND_UTS.find(
    s => s.name.toLowerCase() === stateName.trim().toLowerCase()
  );
  return found ? found.districts : [];
}
